/**
 * Адреса обложек YouTube.
 *
 * Вынесено в отдельный модуль, потому что нужно и сервису поиска, и
 * компонентам интерфейса. Импортировать это из `youtubeSearch` нельзя:
 * вместе с функцией подтянулся бы весь код поиска с перебором зеркал,
 * хотя карточке трека он не нужен.
 */

/**
 * Обложка по идентификатору видео — всегда с CDN Google.
 *
 * Почему не ссылка из ответа зеркала: зеркала отдают превью со СВОЕГО домена
 * (`invidious.example/vi/<id>/mq.jpg`). Такие адреса ломаются вместе с
 * зеркалом или начинают требовать авторизацию, и тогда в списке остаются
 * серые заглушки. Домен `i.ytimg.com` принадлежит Google и не зависит
 * от выбранного зеркала.
 *
 * @param quality `hq` (480×360), `mq` (320×180), `maxres` (1280×720).
 */
export function youTubeCoverUrl(videoId: string, quality = "hq"): string {
  return `https://i.ytimg.com/vi/${videoId}/${quality}default.jpg`;
}

/** Порядок перебора качеств, если предыдущее не загрузилось. */
export const YOUTUBE_COVER_QUALITIES = ["hq", "mq", "maxres"] as const;
