import type { CapacitorConfig } from "@capacitor/cli";

/**
 * Конфигурация нативной оболочки Android.
 *
 * ЗАЧЕМ НУЖНО НАТИВНОЕ ПРИЛОЖЕНИЕ
 * -------------------------------
 * В мобильном БРАУЗЕРЕ фоновое воспроизведение ограничено на уровне
 * платформы: при блокировке экрана система вправе остановить страницу,
 * и обойти это из JavaScript нельзя.
 *
 * В нативной оболочке тот же веб-код работает внутри WebView, но
 * воспроизведением управляет Android: звук продолжается при погашенном
 * экране, работают кнопки в шторке и на экране блокировки.
 *
 * Плюс появляется доступ к нативным запросам — см. `CapacitorHttp` ниже.
 */
const config: CapacitorConfig = {
  appId: "com.noctra.music",
  appName: "Noctra",

  /* Папка со сборкой Vite: именно она упаковывается внутрь приложения. */
  webDir: "dist",

  server: {
    /*
     * Схема внутреннего сервера WebView.
     *
     * `https` выбран намеренно: на `http` движок считает страницу
     * небезопасной и блокирует часть возможностей, включая MediaSession —
     * а от неё зависит управление плеером с экрана блокировки.
     */
    androidScheme: "https",
  },

  android: {
    /*
     * Разрешаем смешанный контент.
     *
     * Бэкенд может быть доступен по http (локальная разработка), и без
     * этого флага WebView заблокировал бы к нему запросы: страница открыта
     * по https, а запрос идёт по http.
     */
    allowMixedContent: true,
  },

  plugins: {
    /**
     * НАТИВНЫЕ HTTP-ЗАПРОСЫ — КЛЮЧЕВОЙ ПЛАГИН ДЛЯ YOUTUBE.
     *
     * ЗАЧЕМ ОН НУЖЕН
     * --------------
     * Ссылки на аудиопоток YouTube отдаются с хоста `googlevideo.com`,
     * и у них НЕТ заголовка `Access-Control-Allow-Origin`. Обычный `fetch`
     * из WebView такой ответ блокирует — это защита браузера, и обойти её
     * средствами JavaScript нельзя.
     *
     * При включённом `CapacitorHttp` запросы уходят через нативный слой
     * Android, где правила CORS не действуют: там запрос выполняет сам
     * телефон, а не страница. Ответ возвращается в WebView уже готовым.
     *
     * Именно это делает возможным воспроизведение YouTube через наш обычный
     * `<audio>` — тот же, что играет Telegram-треки, и потому работающий
     * в фоне при выключенном экране.
     */
    CapacitorHttp: {
      enabled: true,
    },
  },
};

export default config;
